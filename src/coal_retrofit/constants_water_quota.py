"""中国官方水量分配数据：用水总量控制指标口径。

为什么有这个模块。流域水量预算过去是由模拟的天然径流构建的：

    available = qtot x WATER_EXTRACTABLE_FRACTION (0.20) x (1 - existing_withdrawal_share (0.85))

当时的 `optimization/data_prep.py` 就记录了后两个因子无法分别识别（aliased）——求解器只看得到
它们的乘积（0.03）——所以在那个口径下没有任何实验能说清起约束作用的是环境流量标准还是分配规则
（该口径已删除，见 `OptimizationAssumptions` 的水预算注释）。更糟的是，分母是*本地天然径流*，
对华北各流域而言这根本就是错误的量：海河流域每年实际消耗的水都
多于其自身径流，差额靠跨流域调水（南水北调）和地下水超采来弥补。因此，从本地径流的 20% 中
扣除真实的生活 + 灌溉需求，会给海河、黄河、淮河和西北诸河算出负的额度——这是分母造成的
假象，而不是一项发现。

中国自己的水量分配工具没有这个缺陷。最严格水资源管理制度（"三条红线"）按省设定用水总量
上限，这些上限针对的是实际供给的水量，调水与地下水都计在内。使用它们能让分子与分母来自
同一个官方统计体系。

口径——以及其中的陷阱。本模块中的一切都是中国水资源公报 编写说明 2.(7) 所定义的用水量：
以新水取用量为口径的毛取水量（毛用水量），不含厂内循环用水。它不是旧约束所用的耗水口径。

它也不是 `constants.CHINA_WATER_QUOTA_M3_PER_MWH` 的取水定额口径，而把两者混为一谈正是这里
最容易犯的错误。定额标准（水节约〔2019〕373号）刻意不计直流冷却凝汽器过流——这正是它给
直流冷却的额度 0.35-0.72 m3/MWh 在三种冷却系统中最低的原因。公报恰好相反：它把直流火(核)电
冷却用水作为一个具名子列放在工业用水之内（2025 年全国 953.7亿 m3 中占 453.8）。本模块的
上限是针对公报口径的数量执行的，所以必须控制在上限之下的模型项是电厂取水，而不是计量的
定额水量。按定额核算机队用水，会把它对上限的占用低估约 5x。

模型的取水列本身也不在公报的尺度上：其直流冷却强度是 Macknick (2011) 的美国数值
（82.8-116.5 m3/MWh），把它们用到中国的淡水直流冷却机队上，仅煤电就得到 1034亿 m3/yr——
比公报的全国工业取水总量还多。`builders/water_quota.once_through_calibration` 把它们重新
缩放到公报基准上，正如 `builders/water.basin_bias_factors` 把模拟径流重新缩放到官方水资源
量基准上。

刻意不包含的内容。
  * 逐流域上限。国办发〔2013〕2号 附件1 是一个闭合的省级划分（31 行合计恰为
    6350/6700/7000，残差为零）；不存在平行的流域表，而且流域 != 一级区。流域上限必须
    通过分摊推导——见 `builders/water_quota.py`。
  * 长江 2348亿 m3 这个数字。长江流域综合规划（2012-2030 修订版）从未公开发布；这个数字
    没有可引用的公开来源，不得进入论文。
  * 逐流域耗水量。水资源公报 表11 没有耗水列；只公布全国分部门的耗水率。逐流域套用它
    将是一项假设。
"""
